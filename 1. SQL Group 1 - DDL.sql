#Database
CREATE DATABASE eventsphere;
USE eventsphere;

#Tables
CREATE TABLE Genres (
    genre_id INT AUTO_INCREMENT PRIMARY KEY,
    genre_name VARCHAR(50) NOT NULL
);

CREATE TABLE Countries (
    country_id INT AUTO_INCREMENT PRIMARY KEY,
    country_name VARCHAR(50) NOT NULL
);

CREATE TABLE Provinces (
    province_id INT AUTO_INCREMENT PRIMARY KEY,
    province_name VARCHAR(50) NOT NULL,
    population INT NOT NULL
);

CREATE TABLE Cities (
    city_id INT AUTO_INCREMENT PRIMARY KEY,
    city_name VARCHAR(50) NOT NULL,
    province_id INT NOT NULL,
    population INT NOT NULL,
    FOREIGN KEY (province_id) REFERENCES Provinces(province_id)
);

CREATE TABLE Sponsorships_Partners (
    sponsor_id INT AUTO_INCREMENT PRIMARY KEY,
    company_name VARCHAR(100) NOT NULL,
    industry ENUM('Retail', 'Technology', 'Food', 'Entertainment', 'Sports', 'Telecommunications', 'Others') NOT NULL,
    homologated ENUM('Yes', 'No') NOT NULL DEFAULT 'No',
    sponsor_email VARCHAR(100) NOT NULL
);

CREATE TABLE Venues (
    venue_id INT AUTO_INCREMENT PRIMARY KEY,
    venue_name VARCHAR(100) NOT NULL,
    city_id INT NOT NULL,
    attendance_capacity INT NOT NULL,
    FOREIGN KEY (city_id) REFERENCES Cities(city_id)
);

CREATE TABLE Concerts_Events (
    event_id INT AUTO_INCREMENT PRIMARY KEY,
    event_name VARCHAR(100) NOT NULL,
    date_early_bird DATE NOT NULL,
    date_regular_sales DATE NOT NULL,
    date_event DATE NOT NULL,
    hour_start TIME NOT NULL,
    hour_end TIME NOT NULL,
    concert_status ENUM('On going', 'Completed') NOT NULL
);

CREATE TABLE Ticketing_Platforms (
    ticketing_id INT AUTO_INCREMENT PRIMARY KEY,
    company_name VARCHAR(50) NOT NULL,
    payment_days INT NOT NULL
);

CREATE TABLE Budget_Ticketing (
    b_ticketing_id VARCHAR(50) PRIMARY KEY,
    event_id INT NOT NULL,
    ticketing_id INT NOT NULL,
    amount INT NOT NULL,
    payment_status ENUM('Pending', 'Completed') NOT NULL,
    FOREIGN KEY (event_id) REFERENCES Concerts_Events(event_id),
    FOREIGN KEY (ticketing_id) REFERENCES Ticketing_Platforms(ticketing_id)
);

CREATE TABLE Artists (
    artist_id INT AUTO_INCREMENT PRIMARY KEY,
    artist_name VARCHAR(100) NOT NULL,
    genre_id INT NOT NULL,
    age INT NOT NULL,
    country_id INT NOT NULL,
    spotify_monthly_listeners INT NOT NULL,
    instagram_followers INT NOT NULL,
    artist_status ENUM('Active', 'Inactive', 'Retired') NOT NULL DEFAULT 'Active',
    FOREIGN KEY (genre_id) REFERENCES Genres(genre_id),
    FOREIGN KEY (country_id) REFERENCES Countries(country_id)
);

CREATE TABLE Budget_Artists (
    b_artist_id VARCHAR(50) PRIMARY KEY,
    event_id INT NOT NULL,
    artist_id INT NOT NULL,
    amount INT NOT NULL,
    payment_status ENUM('Pending', 'Completed') NOT NULL,
    FOREIGN KEY (event_id) REFERENCES Concerts_Events(event_id),
    FOREIGN KEY (artist_id) REFERENCES Artists(artist_id)
);

CREATE TABLE Budget_Sponsorships (
    b_sponsor_id VARCHAR(50) PRIMARY KEY,
    event_id INT NOT NULL,
    sponsor_id INT NOT NULL,
    amount INT NOT NULL,
    payment_status ENUM('Pending', 'Completed') NOT NULL,
    FOREIGN KEY (event_id) REFERENCES Concerts_Events(event_id),
    FOREIGN KEY (sponsor_id) REFERENCES Sponsorships_Partners(sponsor_id)
);

CREATE TABLE Budget_Venues (
    b_venue_id VARCHAR(50) PRIMARY KEY,
    event_id INT NOT NULL,
    venue_id INT NOT NULL,
    amount INT NOT NULL,
    payment_status ENUM('Pending', 'Completed') NOT NULL,
    FOREIGN KEY (event_id) REFERENCES Concerts_Events(event_id),
    FOREIGN KEY (venue_id) REFERENCES Venues(venue_id)
);

